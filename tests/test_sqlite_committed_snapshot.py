def test_without_rowid_is_reported_unsupported_not_empty(tmp_path):
    db = tmp_path / "without-rowid.db"
    con = sqlite3.connect(db)
    con.execute("CREATE TABLE special(id TEXT PRIMARY KEY, value TEXT) WITHOUT ROWID")
    con.execute("INSERT INTO special VALUES('one','exists')")
    con.commit()
    con.close()
    obs = dftk.get_registry().run("database.sqlite_recover", {"path": str(db)})
    assert obs.status.value == "partial"
    assert obs.facts["unsupported_tables"][0]["table"] == "special"
    assert obs.facts["tables"] == []
