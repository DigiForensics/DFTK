def engine_view(pages, path):
    path.write_bytes(b"".join(pages[i] for i in sorted(pages)))
    con = sqlite3.connect(path.resolve().as_uri() + "?mode=ro&immutable=1", uri=True)
    try:
        return con.execute("SELECT * FROM records").fetchall()
    finally:
        con.close()


def append_frame(wal, page, payload, *, commit_size=0):
    """Independent implementation of the spec checksum for a crafted tail."""
    page_size = int.from_bytes(wal[8:12], "big")
    assert len(payload) == page_size
    seed = struct.unpack(">II", wal[-page_size-8:-page_size])
    first_eight = struct.pack(">II", page, commit_size)
    endian = "<" if wal[:4] == bytes.fromhex("377f0682") else ">"
    words = struct.unpack(endian + "I" * ((8 + page_size)//4), first_eight + payload)
    a, b = seed
    for left, right in zip(words[::2], words[1::2]):
        a = (a + left + b) % (1 << 32)
        b = (b + right + a) % (1 << 32)
    return wal + first_eight + wal[16:24] + struct.pack(">II", a, b) + payload


def test_zero_one_empty_blob_and_text_remain_distinct_against_engine(tmp_path):
    db = tmp_path / "types.db"
    con = sqlite3.connect(db)
    con.execute("CREATE TABLE t(a INTEGER, b INTEGER, c BLOB, d TEXT, e INTEGER)")
    con.execute("INSERT INTO t VALUES(0,1,x'','',NULL)")
    oracle = list(con.execute("SELECT * FROM t"))
    con.commit()
    con.close()
    raw = db.read_bytes()
    hdr = parse_sqlite_header(raw)
    size = hdr["page_size"]
    pages = reconstruct_logical_pages(raw, None, size)
    schema = parse_schema(pages, size, hdr["reserved_bytes_per_page"], hdr["text_encoding"])
    rows = walk_table_leaves(pages, schema[0]["rootpage"], size, hdr["reserved_bytes_per_page"], hdr["text_encoding"])
    assert [tuple(row[2]) for row in rows] == oracle
    assert [type(value) for value in rows[0][2]] == [int, int, bytes, str, type(None)]


def test_engine_committed_wal_reconstruction_is_identical(acquired_wal, tmp_path):
    db, wal, oracle = acquired_wal
    parsed = parse_wal(wal.read_bytes())
    assert parsed["last_commit_index"] is not None
    assert parsed["committed_frame_count"] == parsed["frame_count"]
    detail = {}
    pages = reconstruct_logical_pages(db.read_bytes(), wal.read_bytes(), 512, diagnostics=detail)
    assert engine_view(pages, tmp_path / "snapshot.db") == oracle
    assert detail["applied_frames"] > 0


def test_valid_uncommitted_tail_cannot_replace_committed_record(acquired_wal, tmp_path):
    db, wal, oracle = acquired_wal
    original = wal.read_bytes()
    appended = append_frame(original, 2, b"X" * 512)
    parsed = parse_wal(appended)
    assert parsed["frames"][-1]["valid"] and not parsed["frames"][-1]["commit"]
    assert parsed["committed_frame_count"] == parsed["frame_count"] - 1
    detail = {}
    pages = reconstruct_logical_pages(db.read_bytes(), appended, 512, diagnostics=detail)
    assert engine_view(pages, tmp_path / "snapshot.db") == oracle
    assert any("uncommitted" in warning for warning in detail["warnings"])


def test_invalid_header_checksum_never_applies_frames(acquired_wal, tmp_path):
    db, wal, _ = acquired_wal
    invalid = bytearray(wal.read_bytes())
    invalid[24] ^= 1
    detail = {}
    pages = reconstruct_logical_pages(db.read_bytes(), bytes(invalid), 512, diagnostics=detail)
    assert detail["applied_frames"] == 0
    assert engine_view(pages, tmp_path / "snapshot.db") == []
    assert any("header checksum" in warning for warning in detail["warnings"])


def test_corrupt_frame_cannot_be_followed_by_a_valid_commit(acquired_wal):
    _, wal, _ = acquired_wal
    damaged = bytearray(wal.read_bytes())
    damaged[32+24+20] ^= 1
    damaged = append_frame(bytes(damaged), 2, b"X" * 512, commit_size=2)
    parsed = parse_wal(damaged)
    assert not parsed["frames"][-1]["valid"]
    assert parsed["committed_frame_count"] == 0


def test_partial_wal_tail_is_explicit(acquired_wal):
    db, wal, _ = acquired_wal
    detail = {}
    reconstruct_logical_pages(db.read_bytes(), wal.read_bytes() + b"truncated", 512, diagnostics=detail)
    assert any("truncated WAL" in warning for warning in detail["warnings"])


def test_recovery_returns_live_values_and_wal_provenance_without_source_writes(acquired_wal, tmp_path):
    db, wal, _ = acquired_wal
    before = {path.name: path.read_bytes() for path in db.parent.iterdir()}
    session = CaseSession(tmp_path / "cases")
    cid = session.new()["case_id"]
    obs = session.run(cid, "database.sqlite_recover", {"path": str(db)})
    assert obs.facts["wal_applied"]
    assert obs.facts["live_total"] == 1
    record = obs.facts["live_samples"][0]["records"][0]
    assert record["columns"][:2] == ["committed", 1]
    assert record["columns"][2] == {"type": "blob", "hex": "", "length": 0}
    evidence = next(item for item in obs.evidence if item.kind == "sqlite_live_record")
    assert evidence.source == str(wal)
    assert evidence.source_sha256 == hashlib.sha256(wal.read_bytes()).hexdigest()
    assert evidence.locator.startswith("frame:")
    _, stored = session.read_run(cid, 1)
    assert stored["facts"]["live_total"] == 1
    assert {path.name: path.read_bytes() for path in db.parent.iterdir()} == before


def test_wal_inventory_marks_uncommitted_tail_as_partial(acquired_wal):
    _, wal, _ = acquired_wal
    wal.write_bytes(append_frame(wal.read_bytes(), 2, b"X" * 512))
    obs = dftk.get_registry().run("database.sqlite_wal", {"wal_path": str(wal)})
    assert obs.status.value == "partial"
    assert obs.evidence[-1].state == "PARTIAL"
    assert any("uncommitted" in warning for warning in obs.warnings)


